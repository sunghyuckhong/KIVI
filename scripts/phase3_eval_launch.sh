#!/bin/bash
# Phase 3 eval: 2 models (Llama-3-8B base + R1-Distill-Llama-8B) × 6 methods × 5 tasks.
# Uses modern_env (transformers 4.51.3) + run_eval.py which supports all 6 methods.
# 12 streams total; orchestrates across 4 GPUs in waves via first_free_gpu polling.
set -u
cd /workspace/KIVI
export HF_TOKEN=${HF_TOKEN:?set HF_TOKEN before running}
MODERN=/opt/modernenv/bin/python

BS=16
BENCH="truthfulqa_gen coqa gsm8k_32k gpqa_diamond_cot_n_shot_32k math500_32k"  # reasoning at 32k, non-reasoning at HFLM default 256

# Model short names and HF paths
declare -A MODEL_PATH=(
  [l3_base]="meta-llama/Meta-Llama-3-8B"
  [r1d_l3]="deepseek-ai/DeepSeek-R1-Distill-Llama-8B"
)
declare -A MODEL_SHORT=(
  [l3_base]="meta-llama-3-8b"
  [r1d_l3]="deepseek-r1-distill-llama-8b"
)

# Calib file stems (generated by calibration — see phase3_calib_launch.sh)
# After calibration, variant generation: a=0.75_pair + pairK99p9_pV99p9
# Script assumes calib outputs are at logs/calib/smoothkv_<short>_*.pt and that
# variant-generation has been run before eval start.
declare -A CALIB_A075=(
  [l3_base]="logs/calib/smoothkv_meta-llama-3-8b_a0.75_pair.pt"
  [r1d_l3]="logs/calib/smoothkv_deepseek-r1-distill-llama-8b_a0.75_pair.pt"
)
declare -A CALIB_PK99p9=(
  [l3_base]="logs/calib/smoothkv_meta-llama-3-8b_pairK99p9_pV99p9.pt"
  [r1d_l3]="logs/calib/smoothkv_deepseek-r1-distill-llama-8b_pairK99p9_pV99p9.pt"
)

cmd_stream() {
  # cmd_stream <model_key> <method_tag>
  local mkey=$1 method=$2 mp="${MODEL_PATH[$mkey]}"
  local parts=()
  for t in $BENCH; do
    case "$method" in
      fp16)      parts+=("$MODERN run_eval.py --model fp16     --model_path $mp --task $t --batch_size $BS --k_bits 16 --v_bits 16") ;;
      kivi2)     parts+=("$MODERN run_eval.py --model kivi     --model_path $mp --task $t --batch_size $BS --k_bits 2 --v_bits 2 --group_size 32 --residual 128") ;;
      pertoken)  parts+=("$MODERN run_eval.py --model pertoken --model_path $mp --task $t --batch_size $BS --k_bits 4 --v_bits 4 --group_size 128 --residual 0") ;;
      fp8)       parts+=("$MODERN run_eval.py --model fp8      --model_path $mp --task $t --batch_size $BS --group_size 128") ;;
      smoothkv_a075)    parts+=("$MODERN run_eval.py --model smoothkv --model_path $mp --task $t --batch_size $BS --k_bits 4 --v_bits 4 --group_size 128 --residual 0 --calib_path ${CALIB_A075[$mkey]}") ;;
      smoothkv_pk99p9)  parts+=("$MODERN run_eval.py --model smoothkv --model_path $mp --task $t --batch_size $BS --k_bits 4 --v_bits 4 --group_size 128 --residual 0 --calib_path ${CALIB_PK99p9[$mkey]}") ;;
    esac
  done
  local out=""
  for c in "${parts[@]}"; do out="$out $c ; "; done
  echo "${out% ; }"
}

# 12 streams: (model, method) pairs
STREAMS=(
  "phase3_l3_fp16:l3_base:fp16"
  "phase3_l3_kivi2:l3_base:kivi2"
  "phase3_l3_pertoken:l3_base:pertoken"
  "phase3_l3_fp8:l3_base:fp8"
  "phase3_l3_smoothkv_a075:l3_base:smoothkv_a075"
  "phase3_l3_smoothkv_pk99p9:l3_base:smoothkv_pk99p9"
  "phase3_r1d_fp16:r1d_l3:fp16"
  "phase3_r1d_kivi2:r1d_l3:kivi2"
  "phase3_r1d_pertoken:r1d_l3:pertoken"
  "phase3_r1d_fp8:r1d_l3:fp8"
  "phase3_r1d_smoothkv_a075:r1d_l3:smoothkv_a075"
  "phase3_r1d_smoothkv_pk99p9:r1d_l3:smoothkv_pk99p9"
)

is_free() {
  local g=$1 mem pids
  mem=$(nvidia-smi --id=$g --query-gpu=memory.used --format=csv,noheader,nounits 2>/dev/null | tr -d ' ')
  [ -z "$mem" ] || [ "$mem" -ge 20000 ] && return 1
  pids=$(nvidia-smi --id=$g --query-compute-apps=pid --format=csv,noheader,nounits 2>/dev/null | tr -d ' ')
  [ -n "$pids" ] && return 1
  return 0
}
first_free_gpu() {
  for g in 0 1 2 3; do
    if is_free $g; then echo "$g"; return 0; fi
  done
  return 1
}

# Generate pair-mergeable variants from the calib file (which has both max stats
# and reservoir samples via --samples_per_channel 10000)
for mkey in l3_base r1d_l3; do
  short="${MODEL_SHORT[$mkey]}"
  perc="logs/calib/smoothkv_${short}_perc.pt"
  if [ ! -f "$perc" ]; then
    echo "[phase3-eval] WARNING: $perc missing — calibration likely failed for $mkey"
    continue
  fi
  if [ ! -f "${CALIB_A075[$mkey]}" ]; then
    echo "[phase3-eval] generating ${CALIB_A075[$mkey]}"
    /usr/bin/python scripts/make_alpha_variants.py --base "$perc" --alphas 0.75 --pair_max_k 2>&1 | tail -3
  fi
  if [ ! -f "${CALIB_PK99p9[$mkey]}" ]; then
    echo "[phase3-eval] generating ${CALIB_PK99p9[$mkey]}"
    /usr/bin/python scripts/make_percentile_variants.py --base "$perc" --pk 99.9 --symmetric 2>&1 | tail -3
  fi
done

for entry in "${STREAMS[@]}"; do
  name="${entry%%:*}"
  rest="${entry#*:}"
  mkey="${rest%%:*}"
  method="${rest##*:}"
  while true; do
    gpu=$(first_free_gpu) && break
    sleep 60
  done
  cmd=$(cmd_stream "$mkey" "$method")
  echo "[phase3-eval] launching $name on GPU$gpu"
  bash scripts/launch_wave.sh "$name" "$gpu" "$cmd"
  sleep 20
done
echo "[phase3-eval] all 12 Phase-3 streams launched."
